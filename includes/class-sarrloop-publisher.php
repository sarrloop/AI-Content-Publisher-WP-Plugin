<?php

defined( 'ABSPATH' ) || exit;

/**
 * WordPress publisher.
 */
class Sarrloop_AI_Publisher {

	/**
	 * Publish article.
	 *
	 * @param array $article Article data.
	 * @param bool  $manual  Manual generation.
	 * @return int|WP_Error
	 */
	public static function publish( $article, $manual = false, $generate_image = null ) {

		$settings = Sarrloop_AI_Settings::get();

        /*
        * If image generation wasn't explicitly specified,
        * use the plugin setting.
        */
        if ( null === $generate_image ) {
            $generate_image = ! empty( $settings['generate_image'] );
        }

		if ( empty( $article['title'] ) || empty( $article['content'] ) ) {

			return new WP_Error(
				'invalid_article',
				__( 'Invalid article data.', 'sarrloop-ai-content-publisher' )
			);
		}

		$content = $article['content'];

		/*
		 * Internal links.
		 */
		if ( ! empty( $settings['add_internal_links'] ) ) {
			$content = self::add_internal_links(
				$content,
				$settings['max_internal_links']
			);
		}

		/*
		 * Promotional link.
		 */
		if ( ! empty( $settings['add_promo_link'] ) ) {
			$content .= self::get_promo_block();
		}

		$post_status = $settings['post_status'];

		$post_author = absint( $settings['author_id'] );

		if ( ! $post_author ) {
			$post_author = get_current_user_id();

			if ( ! $post_author ) {
				$post_author = 1;
			}
		}

		$post_data = array(
			'post_title'   => sanitize_text_field( $article['title'] ),
			'post_content' => wp_kses_post( $content ),
			'post_excerpt' => sanitize_textarea_field( $article['excerpt'] ),
			'post_status'  => $post_status,
			'post_type'    => 'post',
			'post_author'  => $post_author,
		);

		if ( ! empty( $settings['category_id'] ) ) {
			$post_data['post_category'] = array(
				absint( $settings['category_id'] ),
			);
		}

		$post_id = wp_insert_post(
			wp_slash( $post_data ),
			true
		);

		if ( is_wp_error( $post_id ) ) {
			return $post_id;
		}

		/*
		 * Tags.
		 */
		if ( ! empty( $article['tags'] ) ) {

			wp_set_post_tags(
				$post_id,
				$article['tags'],
				false
			);
		}

		/*
		 * SEO meta.
		 */
		if ( ! empty( $settings['generate_seo'] ) ) {

			$meta_description = sanitize_text_field(
				$article['meta_description']
			);

			$focus_keyword = sanitize_text_field(
				$article['focus_keyword']
			);

			/*
			 * Yoast SEO.
			 */
			update_post_meta(
				$post_id,
				'_yoast_wpseo_metadesc',
				$meta_description
			);

			update_post_meta(
				$post_id,
				'_yoast_wpseo_focuskw',
				$focus_keyword
			);

			/*
			 * Rank Math SEO.
			 */
			update_post_meta(
				$post_id,
				'rank_math_description',
				$meta_description
			);

			update_post_meta(
				$post_id,
				'rank_math_focus_keyword',
				$focus_keyword
			);

			/*
			 * All in One SEO (AIOSEO).
			 */
			update_post_meta(
				$post_id,
				'_aioseo_description',
				$meta_description
			);

			update_post_meta(
				$post_id,
				'_aioseo_keywords',
				$focus_keyword
			);

			/*
			 * Also store generic plugin metadata.
			 */
			update_post_meta(
				$post_id,
				'_sarrloop_ai_meta_description',
				$meta_description
			);

			update_post_meta(
				$post_id,
				'_sarrloop_ai_focus_keyword',
				$focus_keyword
			);
		}

		/*
		 * Store topic.
		 */
		if ( ! empty( $article['topic'] ) ) {

			update_post_meta(
				$post_id,
				'_sarrloop_ai_topic',
				sanitize_text_field( $article['topic'] )
			);
		}

		/*
		 * Generated by plugin.
		 */
		update_post_meta(
			$post_id,
			'_sarrloop_ai_generated',
			'1'
		);

		/*
        * Generate featured image only when explicitly requested.
        */
        if ( $generate_image ) {

            $image_id = Sarrloop_AI_Image::generate(
                $article['title'],
                $article['topic']
            );

            if ( is_wp_error( $image_id ) ) {

                Sarrloop_AI_Logger::add(
                    'Featured image failed: ' .
                    $image_id->get_error_message(),
                    'warning'
                );

            } elseif ( absint( $image_id ) > 0 ) {

                set_post_thumbnail(
                    $post_id,
                    absint( $image_id )
                );

            } else {

                Sarrloop_AI_Logger::add(
                    'Featured image failed: Unknown image-generation error.',
                    'warning'
                );
            }
        }

		Sarrloop_AI_Logger::add(
			sprintf(
				'Article created successfully: #%d - %s',
				$post_id,
				$article['title']
			),
			'success'
		);

		return $post_id;
	}

	/**
	 * Add internal links.
	 *
	 * @param string $content Content.
	 * @param int    $limit   Limit.
	 * @return string
	 */
	private static function add_internal_links( $content, $limit = 3 ) {

		$limit = absint( $limit );

		if ( $limit < 1 ) {
			return $content;
		}

		$posts = get_posts(
			array(
				'post_type'      => 'post',
				'post_status'    => 'publish',
				'posts_per_page' => $limit,
				'orderby'        => 'date',
				'order'          => 'DESC',
			)
		);

		if ( empty( $posts ) ) {
			return $content;
		}

		$links = array();

		foreach ( $posts as $post ) {

			$links[] = sprintf(
				'<p><strong>%s:</strong> <a href="%s">%s</a></p>',
				esc_html__( 'Related', 'sarrloop-ai-content-publisher' ),
				esc_url( get_permalink( $post->ID ) ),
				esc_html( get_the_title( $post->ID ) )
			);
		}

		return $content . implode( "\n", $links );
	}

	/**
	 * Promotional CTA.
	 *
	 * @return string
	 */
	private static function get_promo_block() {

		$settings = Sarrloop_AI_Settings::get();

		if ( empty( $settings['links'] ) ) {
			return '';
		}

		$active_links = array();

		foreach ( $settings['links'] as $link ) {

			if (
				! empty( $link['active'] ) &&
				! empty( $link['url'] ) &&
				! empty( $link['text'] )
			) {
				$active_links[] = $link;
			}
		}

		if ( empty( $active_links ) ) {
			return '';
		}

		$link    = $active_links[ array_rand( $active_links ) ];
		$heading = ! empty( $settings['promo_heading'] )
			? sanitize_text_field( $settings['promo_heading'] )
			: __( 'Recommended Resource', 'sarrloop-ai-content-publisher' );

		return sprintf(
			'
<div class="sarrloop-ai-cta">
	<p><strong>%s</strong></p>
	<p><a href="%s" target="_blank" rel="noopener noreferrer">%s</a></p>
</div>',
			esc_html( $heading ),
			esc_url( $link['url'] ),
			esc_html( $link['text'] )
		);
	}
}